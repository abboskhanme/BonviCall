"""Call ACTIVITY — volume and answerability. **Read only.**

Ported from BonviZvonki ``modules/analytics/application/activity.py``
(``ActivityService``). Every query, every join and every reason for them is
theirs; what changed is named at each seam below. The terms this report uses —
and why "unanswered" is never one number — are in ``rules.py``.

This module owns no table and is declared in ``core/reads.py``
(CONVENTIONS.md §2.1), so three rules bind it and ``tests/test_layering.py``
checks all three: it reads only ``calls.CallModel`` and ``agents.AgentModel``,
it never writes, and it never selects a bare ORM entity — only projections and
aggregates, so nothing foreign can escape past this boundary.

════════════════════════════════════════════════════════════════
 THE SEAMS THAT CHANGED, AND WHY
════════════════════════════════════════════════════════════════

**The phone key is a column, not an expression.** BonviZvonki matches
customers with
``right(regexp_replace(coalesce(calls.client_phone,''),'\\D','','g'), 9)``
written as a ``literal_column`` — with a long comment about bind parameters:
``func.coalesce(column, "")`` turns the empty string into ``$1``, the same
expression in SELECT and in GROUP BY then gets two different parameter
numbers, PostgreSQL calls them different expressions and raises
"client_phone must appear in the GROUP BY clause". BonviCall has
``calls.remote_number_key``, a STORED generated column produced by
``core.phone.phone_key_sql`` and indexed by ``ix_calls_remote``, so the whole
problem and its workaround disappear. ``length(tail) = 9`` becomes
``remote_number_key IS NOT NULL``, which is the same test: the generated
column is NULL for anything shorter, deliberately (N37 — a 4-digit extension
used as a key matches the tail of every long number).

**Answered/unanswered is a NOT NULL enum here**, so the ``unknown`` family and
the ``inbound_known`` denominator are gone. ``rules.py`` says why in full.

**The window is whole Asia/Tashkent days**, resolved once in
``rules.activity_window`` and passed in, so this module never touches a clock.

**Own-scope narrowing is this module's job.** A ``sales`` principal holds
``calls:read:own`` and the query is narrowed to their own agent, exactly as
``CallService._scoped`` does it — the permission decides, the query narrows,
and there is never a second check (CONVENTIONS.md §11).
"""

